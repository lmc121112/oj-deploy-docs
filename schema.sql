-- ONLINE JUDGE OPEN-SOURCE - SUPABASE DATABASE SCHEMA
-- ============================================================================

-- 1. Bảng người dùng
CREATE TABLE IF NOT EXISTS public.users (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  username TEXT UNIQUE NOT NULL,
  password TEXT NOT NULL,
  role TEXT NOT NULL DEFAULT 'user',
  created_at TIMESTAMPTZ DEFAULT NOW()
);

-- 2. Bảng kỳ thi (Contests)
CREATE TABLE IF NOT EXISTS public.contests (
  id TEXT PRIMARY KEY,
  title TEXT NOT NULL,
  start_time TIMESTAMPTZ NOT NULL,
  end_time TIMESTAMPTZ NOT NULL,
  restrict_users BOOLEAN DEFAULT FALSE,
  allowed_users TEXT[] DEFAULT '{}',
  created_at TIMESTAMPTZ DEFAULT NOW()
);

-- 3. Bảng đề bài (Problems)
CREATE TABLE IF NOT EXISTS public.problems (
  id TEXT PRIMARY KEY,
  title TEXT NOT NULL,
  statement TEXT DEFAULT '',
  time_limit_ms INT DEFAULT 1000,
  memory_limit_mb INT DEFAULT 256,
  contest_id TEXT REFERENCES public.contests(id) ON DELETE SET NULL,
  problem_order INT DEFAULT 1,
  io_mode TEXT DEFAULT 'stdio',
  io_filename TEXT DEFAULT '',
  hide_tests BOOLEAN DEFAULT FALSE,
  hide_grading BOOLEAN DEFAULT FALSE,
  created_at TIMESTAMPTZ DEFAULT NOW()
);

-- 4. Bảng bộ test (Test Cases)
CREATE TABLE IF NOT EXISTS public.test_cases (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  problem_id TEXT REFERENCES public.problems(id) ON DELETE CASCADE,
  test_order INT NOT NULL DEFAULT 1,
  input_data TEXT NOT NULL,
  expected_output TEXT NOT NULL
);

-- 5. Bảng lịch sử bài nộp (Submissions)
CREATE TABLE IF NOT EXISTS public.submissions (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  problem_id TEXT REFERENCES public.problems(id) ON DELETE CASCADE,
  username TEXT NOT NULL,
  language TEXT NOT NULL,
  source_code TEXT NOT NULL,
  status TEXT DEFAULT 'Pending',
  verdict TEXT DEFAULT '',
  exec_time_ms INT DEFAULT 0,
  memory_kb INT DEFAULT 0,
  compile_message TEXT DEFAULT '',
  test_results JSONB DEFAULT '[]'::jsonb,
  created_at TIMESTAMPTZ DEFAULT NOW()
);

-- 6. Bảng Template code mặc định theo ngôn ngữ
CREATE TABLE IF NOT EXISTS public.language_templates (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  language TEXT UNIQUE NOT NULL,
  display_name TEXT NOT NULL,
  template_code TEXT NOT NULL
);

